"""Write results/summary.md from eval JSONL. Numbers come only from those files."""

from __future__ import annotations

import json
from pathlib import Path


def load_runs(results_dir: Path) -> list[dict]:
    runs = []
    root = Path(results_dir)
    if not root.is_dir():
        return runs
    for path in sorted(root.rglob("*.jsonl")):
        summary = None
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("record") == "summary":
                summary = row
        if summary is not None:
            summary = dict(summary)
            summary["path"] = str(path)
            runs.append(summary)
    return runs


def render_summary(runs: list[dict]) -> str:
    lines = [
        "# S4a evaluation",
        "",
        "Generated by `coopx.eval.report` from the JSONL files below. No hand-edited numbers.",
        "",
        "Tune/report split: frame `000096` is the tune fixture until occlusion-mined clips",
        "exist. It is **not** an occluded-target clip (`outside_view` from the ego, not",
        "`occluded`). Report clips are whatever `data/scenes/scenes.json` names when Agent A's",
        "miner has landed; otherwise this table is the fixture only.",
        "",
        "Fusion `geo` and `witness` use `coopx.eval.fusion` when that module imports, and a",
        "labelled stub otherwise. The stub does not apply real-LiDAR free-space contradiction.",
        "Muse fusion is S4b and is absent here.",
        "",
        "| scene | fusion | attack | stub | occluded recall | precision | false hazards | flips | caught | messages | roots | partial |",
        "|---|---|---|---|---:|---:|---:|---:|---|---:|---:|---|",
    ]
    if not runs:
        lines.append("| — | — | — | — | — | — | — | — | — | — | — | — |")
    for run in runs:
        metrics = run.get("metrics") or {}
        scores = metrics.get("scores") or {}
        roots = metrics.get("independence") or {}
        lines.append("| {scene} | {fusion} | {attack} | {stub} | {recall} | {precision} | {false} | {flips} | {caught} | {messages} | {roots} | {partial} |".format(
            scene=run.get("scene", ""),
            fusion=run.get("fusion", ""),
            attack=run.get("attack") or "—",
            stub="yes" if run.get("fusion_stub") else "no",
            recall=_fmt(scores.get("occluded_recall")),
            precision=_fmt(scores.get("precision")),
            false=scores.get("false_hazards", ""),
            flips=metrics.get("safety_flips", ""),
            caught=_caught(metrics.get("attack_caught")),
            messages=roots.get("messages", ""),
            roots=roots.get("independent_roots", ""),
            partial="yes" if run.get("partial") else "no",
        ))
    ego = _ego_note(runs)
    if ego:
        lines.extend(["", "## Ego camera on the tune frame", "", ego, ""])
    lines.extend(["", "## Runs", ""])
    for run in runs:
        lines.append(f"- `{run.get('path', '')}`")
    lines.append("")
    return "\n".join(lines)


def write_summary(results_dir: Path, out: Path) -> str:
    text = render_summary(load_runs(results_dir))
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return text


def _ego_note(runs) -> str:
    for run in runs:
        path = Path(run.get("path") or "")
        if len(path.parents) < 2:
            continue
        note = path.parents[1] / "ego-000096.json"
        if note is not None and note.is_file():
            data = json.loads(note.read_text(encoding="utf-8"))
            cams = ", ".join(f"{name}={state}" for name, state in data.get("cameras", {}).items())
            return (f"Frame {data.get('frame_id')} pedestrian {data.get('pedestrian_id')}: {cams}. "
                    f"SAM on {data.get('camera')} published {data.get('published', 0)}; "
                    f"nearest lift {data.get('nearest_m')} m; cost ${data.get('cost_usd', 0)}. "
                    f"{data.get('note', '')}")
    return ""


def _fmt(value) -> str:
    if value is None:
        return "n/a"
    return f"{float(value):.3f}"


def _caught(value) -> str:
    if value is None:
        return "—"
    return "yes" if value else "no"
