"""Write results/summary.md from eval JSONL. Numbers come only from those files."""

from __future__ import annotations

import json
from pathlib import Path


def load_runs(results_dir: Path) -> list[dict]:
    runs = []
    root = Path(results_dir)
    if not root.is_dir():
        return runs
    for path in sorted(root.rglob("*.jsonl")):
        summary = None
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("record") == "summary":
                summary = row
        if summary is not None:
            summary = dict(summary)
            summary["path"] = str(path)
            runs.append(summary)
    return runs


def render_summary(runs: list[dict]) -> str:
    lines = [
        "# Witness evaluation (S4a, deterministic fusion; Muse off)",
        "",
        "Generated by `coopx.eval.report` from the JSONL result files. No hand-edited numbers.",
        "",
        "**Replay.** Causal: observers run SAM at 2 Hz from 3 s before each mined clip to 3 s",
        "after it; detections enter only at their measured availability time (cached calls",
        "replay their original latency). Roadside units publish real-LiDAR free space. Remote",
        "packets cross the link into the ego's checker; ego cameras stay local. Fusion runs at",
        "every 10 Hz frame on what has arrived.",
        "",
        "**Scoring.** Precision is one-to-one against *all* labelled objects within the stated",
        "radius of the ego; extra beliefs on an already-matched object are *duplicates* (one",
        "object seen by several observers), beliefs outside the radius are *out of region*;",
        "neither counts as a false hazard. Occluded recall counts only frames whose ego",
        "visibility label is `occluded` (FOV alone is not occlusion). Lead time is first",
        "warning to the ego's first labelled-visible frame; `n/a` = no warning or the ego",
        "never sees the target in the window (censored, not success).",
        "",
        "**Split.** `report` = mined clips (`data/scenes/scenes.json`, provisional labels,",
        "human review pending). `tune` = the S3 frame (pedestrian outside the ego's view,",
        "not occluded). No parameters were tuned on report clips.",
        "",
        "**Modes.** `ego` own sensors only; `union` every admitted remote claim (absence claims",
        "never delete a local detection); `geo` object-level geometric consensus inspired by",
        "ROBOSAC/CAD (>=2 physical bodies within 1.5 m / 3 m and 300 ms; eligible range free",
        "space contradicts), not a reproduction; `witness` authenticated-root assessment.",
        "`replay_refreshed` is not caught by design: a fresh capture time with the attacker's",
        "own valid signature passes freshness. `independent witnesses` follows EvidenceStore:",
        "unanchored identities count zero; relays of one observation count once.",
        "",
        "Main rows use SAM perception. `gt-oracle` places targets at ground truth when labelled",
        "visible; it is a comparison, not a result.",
        "",
    ]
    lines.extend(_table(run for run in runs if run.get("perception", "sam") == "sam"))
    oracle = [run for run in runs if run.get("perception") == "gt-oracle"]
    if oracle:
        lines.extend(["", "## Comparison: gt-oracle perception (not a result)", ""])
        lines.extend(_table(oracle))
    if any(run.get("error") for run in runs):
        lines.extend(["", "## Errors and partial runs", ""])
        for run in runs:
            if run.get("error"):
                lines.append(f"- {run.get('scene')} {run.get('perception')} {run.get('fusion')} "
                             f"{run.get('attack') or '—'}: {run['error']}")
    lines.append("")
    return "\n".join(lines)


def _table(runs) -> list[str]:
    rows = sorted(runs, key=lambda r: (r.get("split") != "report", r.get("scene", ""),
                                       r.get("attack") or "", r.get("fusion", "")))
    lines = [
        "| split | scene | attack | fusion | occluded recall | lead (s) | precision | TP | dup | false | out | flips | caught | msgs | indep. witnesses |",
        "|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|",
    ]
    if not rows:
        lines.append("| — |" + " — |" * 14)
    for run in rows:
        m = run.get("metrics") or {}
        sc = m.get("scores") or {}
        ind = m.get("independence") or {}
        leads = [v for v in (m.get("lead_us") or {}).values() if v is not None]
        lines.append("| {split} | {scene} | {attack} | {fusion} | {recall} | {lead} | {precision} | {tp} | {dup} | {false} | {out} | {flips} | {caught} | {msgs} | {wit} |".format(
            split=run.get("split", ""), scene=run.get("scene", ""), attack=run.get("attack") or "—",
            fusion=run.get("fusion", ""), recall=_fmt(sc.get("occluded_recall")),
            lead="n/a" if not leads else f"{min(leads) / 1e6:.1f}",
            precision=_fmt(sc.get("precision")), tp=sc.get("true_positives", ""),
            dup=sc.get("duplicates", ""), false=sc.get("false_hazards", ""),
            out=sc.get("out_of_region", ""), flips=m.get("safety_flips", ""),
            caught=_caught(m.get("attack_caught")), msgs=ind.get("messages", ""),
            wit=ind.get("independent_witnesses", "")))
    return lines


def write_summary(results_dir: Path, out: Path) -> str:
    text = render_summary(load_runs(results_dir))
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return text


def _ego_note(runs) -> str:
    for run in runs:
        path = Path(run.get("path") or "")
        if len(path.parents) < 2:
            continue
        note = path.parents[1] / "ego-000096.json"
        if note is not None and note.is_file():
            data = json.loads(note.read_text(encoding="utf-8"))
            cams = ", ".join(f"{name}={state}" for name, state in data.get("cameras", {}).items())
            return (f"Frame {data.get('frame_id')} pedestrian {data.get('pedestrian_id')}: {cams}. "
                    f"SAM on {data.get('camera')} published {data.get('published', 0)}; "
                    f"nearest lift {data.get('nearest_m')} m; cost ${data.get('cost_usd', 0)}. "
                    f"{data.get('note', '')}")
    return ""


def _fmt(value) -> str:
    if value is None:
        return "n/a"
    return f"{float(value):.3f}"


def _caught(value) -> str:
    if value is None:
        return "—"
    return "yes" if value else "no"
